  /* 대응표 키는 `<대단원 번호>|<우리 아티클명>`이다 — 파일명(articleId)이 아니라 meta에서 바로
     만들 수 있는 값이라, 아직 퀴즈 파일이 없는 대단원(에필로그)도 미리 적어 둘 수 있다. */
